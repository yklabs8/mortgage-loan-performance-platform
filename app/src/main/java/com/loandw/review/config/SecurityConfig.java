package com.loandw.review.config;

import java.util.Map;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.HttpMethod;
import org.springframework.security.authentication.LockedException;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.security.web.SecurityFilterChain;
import org.springframework.security.web.authentication.ExceptionMappingAuthenticationFailureHandler;

/**
 * Login and authorization.
 * <ul>
 *   <li>Form login with passwords compared as BCrypt hashes (the database stores only hashes); 5 wrong passwords in a row lock the account for 15 minutes, with a separate message on the login page while locked</li>
 *   <li>Role-based authorization: assigning, closing, and escalating are manager-only; the service layer checks again against the database (two lines of defense)</li>
 *   <li>CSRF protection is on by default: every form carries a token, and submissions forged by other sites are rejected</li>
 *   <li>CSP response header: only scripts and styles from this site load, so even a script written into a note is not executed by the browser (the second line of defense against XSS;
 *       the first is Thymeleaf's automatic output escaping)</li>
 * </ul>
 */
@Configuration
public class SecurityConfig {

    /** Manager role (OLTP app_role.role_code = MANAGER). */
    private static final String MANAGER = "MANAGER";

    @Bean
    public SecurityFilterChain securityFilterChain(HttpSecurity http) throws Exception {
        http.authorizeHttpRequests(auth -> auth
                .requestMatchers("/css/**", "/login", "/error").permitAll()
                .requestMatchers("/candidates/generate").denyAll()
                .requestMatchers(HttpMethod.POST, "/cases/*/assign", "/cases/*/decide").hasRole(MANAGER)
                .anyRequest().authenticated())
            .formLogin(form -> form.loginPage("/login").defaultSuccessUrl("/", true).permitAll()
                .failureHandler(loginFailureHandler()))
            .logout(logout -> logout.logoutSuccessUrl("/login?logout"))
            .headers(headers -> headers.contentSecurityPolicy(csp -> csp.policyDirectives(
                "default-src 'self'; script-src 'self'; style-src 'self'; frame-ancestors 'none'")));
        return http.build();
    }

    /** A failed login returns to the login page: locked accounts get ?locked, everything else (wrong user name or password, inactive) gets ?error, without revealing which. */
    private static ExceptionMappingAuthenticationFailureHandler loginFailureHandler() {
        var handler = new ExceptionMappingAuthenticationFailureHandler();
        handler.setDefaultFailureUrl("/login?error");
        handler.setExceptionMappings(Map.of(LockedException.class.getName(), "/login?locked"));
        return handler;
    }

    @Bean
    public PasswordEncoder passwordEncoder() {
        // Cost 10: matches the hashes generated by scripts/11_set_demo_passwords.sh; the $2y$ format is accepted too
        return new BCryptPasswordEncoder(10);
    }
}
